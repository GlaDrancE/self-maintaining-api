// Replay a real upstream breaking change: OpenAI's published spec on 2023-06-19,
// commit d9c3021a "remove disabled/deprecated endpoints". The baseline is the spec
// one commit earlier. Both URLs are pinned to commit SHAs, so this never drifts.
import { writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const sma = join(here, '..', '..', 'sma.mjs');
const config = join(here, 'watch.yaml');
const SPEC = 'https://raw.githubusercontent.com/openai/openai-openapi';
const BEFORE = `${SPEC}/a27cad2f601ad3a91d13931dd8679c3042bbae94/openapi.yaml`;
const AFTER = `${SPEC}/d9c3021a243c502a902d71c88b60800151425bf7/openapi.yaml`;

const writeConfig = (spec) =>
  writeFileSync(config, `# Generated by run.mjs.\nrepo: ./app\napis:\n  - name: openai\n    spec: ${spec}\n    baseUrl: https://api.openai.com/v1\n`);
const run = (...args) => spawnSync(process.execPath, [sma, ...args, '--config', config], { stdio: 'inherit' }).status;

writeConfig(BEFORE);
run('reset');
console.log('\n== baseline: openai spec before 2023-06-19 ==');
run('check', '--no-llm');

writeConfig(AFTER);
console.log('\n== upstream ships commit d9c3021a ==');
process.exitCode = run('run', '--no-llm');
